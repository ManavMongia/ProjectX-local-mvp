-- Migration: Broker Lead Status Management
-- Supports five lead statuses: 'New Lead', 'Site Visit Requested', 'Site Visit Done', 'Follow-up', 'Not Interested'
-- Default value: 'New Lead'

-- 1. Add lead_status column to inquiries if not exists
ALTER TABLE public.inquiries 
ADD COLUMN IF NOT EXISTS lead_status TEXT NOT NULL DEFAULT 'New Lead';

-- 2. Add or update check constraint on inquiries.lead_status
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM pg_constraint 
        WHERE conname = 'check_inquiries_lead_status'
    ) THEN
        ALTER TABLE public.inquiries DROP CONSTRAINT check_inquiries_lead_status;
    END IF;

    ALTER TABLE public.inquiries
    ADD CONSTRAINT check_inquiries_lead_status
    CHECK (lead_status IN (
        'New Lead',
        'Site Visit Requested',
        'Site Visit Done',
        'Follow-up',
        'Not Interested'
    ));
END $$;

-- 3. Add index on inquiries for lead_status and broker_id
CREATE INDEX IF NOT EXISTS idx_inquiries_lead_status ON public.inquiries(lead_status);
CREATE INDEX IF NOT EXISTS idx_inquiries_broker_lead_status ON public.inquiries(broker_id, lead_status);

-- 4. Create lead_status_history table
CREATE TABLE IF NOT EXISTS public.lead_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id BIGINT NOT NULL REFERENCES public.inquiries(id) ON DELETE CASCADE,
    old_status TEXT,
    new_status TEXT NOT NULL,
    changed_by UUID REFERENCES auth.users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_lead_status_history_inquiry ON public.lead_status_history(inquiry_id, created_at DESC);

-- 5. Enable Row Level Security (RLS) on lead_status_history
ALTER TABLE public.lead_status_history ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if any
DROP POLICY IF EXISTS "Brokers can view history for their own inquiries" ON public.lead_status_history;
DROP POLICY IF EXISTS "Staff can view all lead status history" ON public.lead_status_history;
DROP POLICY IF EXISTS "Authorized users can insert lead status history" ON public.lead_status_history;

-- Policy: Brokers can view history for inquiries belonging to their broker_id
CREATE POLICY "Brokers can view history for their own inquiries"
ON public.lead_status_history
FOR SELECT
USING (
    EXISTS (
        SELECT 1 FROM public.inquiries i
        WHERE i.id = lead_status_history.inquiry_id
        AND i.broker_id = auth.uid()
    )
);

-- Policy: Staff (Admin / Employee) can view all lead status history
CREATE POLICY "Staff can view all lead status history"
ON public.lead_status_history
FOR SELECT
USING (
    EXISTS (
        SELECT 1 FROM public.profiles p
        WHERE p.id = auth.uid()
        AND p.role IN ('Admin', 'Employee')
    )
);

-- Policy: Authorized users can insert lead status history
CREATE POLICY "Authorized users can insert lead status history"
ON public.lead_status_history
FOR INSERT
WITH CHECK (
    auth.uid() IS NOT NULL AND (
        changed_by = auth.uid() OR changed_by IS NULL
    )
);

-- 6. Atomic PostgreSQL Function for Updating Lead Status
CREATE OR REPLACE FUNCTION public.fn_update_lead_status(
    p_inquiry_id BIGINT,
    p_new_status TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
    v_inquiry public.inquiries%ROWTYPE;
    v_old_status TEXT;
    v_caller_id UUID;
    v_caller_role TEXT;
    v_history_id BIGINT;
    v_result JSONB;
BEGIN
    v_caller_id := auth.uid();

    -- Validate new status against allowed values
    IF p_new_status NOT IN ('New Lead', 'Site Visit Requested', 'Site Visit Done', 'Follow-up', 'Not Interested') THEN
        RAISE EXCEPTION 'Invalid lead status: %', p_new_status;
    END IF;

    -- Fetch the target inquiry
    SELECT * INTO v_inquiry FROM public.inquiries WHERE id = p_inquiry_id;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Inquiry with ID % not found.', p_inquiry_id;
    END IF;

    -- Check caller role
    SELECT role INTO v_caller_role FROM public.profiles WHERE id = v_caller_id;

    -- Ownership check: caller must be authenticated and either the broker or staff
    IF v_caller_id IS NULL THEN
        RAISE EXCEPTION 'Authentication required.';
    END IF;

    IF v_inquiry.broker_id IS NOT NULL AND v_inquiry.broker_id != v_caller_id AND (v_caller_role IS NULL OR v_caller_role NOT IN ('Admin', 'Employee')) THEN
        RAISE EXCEPTION 'Unauthorized: You can only update status for your own leads.';
    END IF;

    v_old_status := COALESCE(v_inquiry.lead_status, 'New Lead');

    -- Update inquiry
    UPDATE public.inquiries
    SET lead_status = p_new_status
    WHERE id = p_inquiry_id;

    -- Insert audit log
    INSERT INTO public.lead_status_history (inquiry_id, old_status, new_status, changed_by, created_at)
    VALUES (p_inquiry_id, v_old_status, p_new_status, v_caller_id, NOW())
    RETURNING id INTO v_history_id;

    -- Dispatch broker notification
    IF v_inquiry.broker_id IS NOT NULL AND v_old_status != p_new_status THEN
        INSERT INTO public.notifications (user_id, title, message, read, created_at)
        VALUES (
            v_inquiry.broker_id,
            'Lead Status Updated',
            'Lead status for "' || COALESCE(v_inquiry.name, 'Customer') || '" updated to ' || p_new_status || '.',
            false,
            NOW()
        );
    END IF;

    v_result := jsonb_build_object(
        'success', true,
        'inquiry_id', p_inquiry_id,
        'old_status', v_old_status,
        'new_status', p_new_status,
        'history_id', v_history_id
    );

    RETURN v_result;
END;
$$;

-- Restrict execution to authenticated users
REVOKE ALL ON FUNCTION public.fn_update_lead_status(BIGINT, TEXT) FROM PUBLIC;
GRANT EXECUTE ON FUNCTION public.fn_update_lead_status(BIGINT, TEXT) TO authenticated;

